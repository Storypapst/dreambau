// A bracket marks one playable letter and its plausible alternatives.
// Example: Han[d|t] offers t at the final d. All positions are zero-based.
function spellingGroup(tier, pattern, entries) {
  return entries.map(([spelling, hint, speech]) => {
    let text = '';
    const traps = {};
    for (const part of spelling.matchAll(/\[([\p{L}])\|([\p{L}]+)\]|([\p{L}])/gu)) {
      if (part[1]) traps[text.length] = part[2];
      text += part[1] ?? part[3];
    }
    const task = { id: 'de-' + text.toLowerCase(), text, tier, level: tier, pattern, hint, traps };
    if (speech) task.speech = speech;
    return task;
  });
}

